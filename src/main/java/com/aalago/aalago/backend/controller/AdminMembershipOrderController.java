package com.aalago.aalago.backend.controller;

import com.aalago.aalago.backend.dto.ApiResponse;
import com.aalago.aalago.backend.dto.MembershipOrderDto;
import com.aalago.aalago.backend.repository.MembershipOrderRepository;
import java.util.List;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;


@RestController
@RequestMapping("/api/admin/membership-orders")
public class AdminMembershipOrderController {
  private final MembershipOrderRepository orders;

  public AdminMembershipOrderController(MembershipOrderRepository orders) {
    this.orders = orders;
  }

  @GetMapping
  ApiResponse<List<MembershipOrderDto>> list() {
    return new ApiResponse<>(orders.orders().stream().map(MembershipOrderDto::from).toList());
  }
}













































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































